/**
 * Converts between `List<PathData>` (your canvas's own stroke model) and an SVG string
 * suitable for attaching to a CalDAV note (e.g. as a base64-encoded `ATTACH` property
 * with `FMTTYPE=image/svg+xml`).
 *
 * The exported SVG is dual-purpose:
 *  1. Standard `<path>` elements make the drawing viewable in *any* SVG-capable client.
 *  2. An embedded `<metadata>` block preserves the exact `PathData` list (id, color,
 *     thickness, every point) so this app — and only this app — can losslessly
 *     reconstruct it on import.
 *
 * Importing deliberately trusts only that metadata block, never the visible `<path>`
 * geometry. See [fromSvg].
 */
object PathDataSvgConverter {

    data class DrawingData(
        val paths: List<PathData>,
        val width: Float,
        val height: Float
    )

    /**
     * Serializes a list of [PathData] (one per stroke) to an SVG document string.
     *
     * Each stroke becomes one `<path>` element. The path geometry uses quadratic Bézier
     * segments — control point at the midpoint of each consecutive point pair, endpoint
     * at the next point — mirroring the smoothing `DrawingCanvas.drawPath()` applies at
     * render time, so the exported SVG visually matches what your canvas shows. A
     * trailing `<metadata>` CDATA block encodes the exact `PathData` (id, color,
     * thickness, raw points) for lossless round-tripping via [fromSvg].
     *
     * @param paths The strokes to serialize, in draw order.
     * @param canvasWidth Width of the canvas the strokes were drawn on, used for the
     *   SVG `viewBox`. If `null`, it's derived from the maximum x-coordinate across all
     *   points (assumes the canvas origin is at `(0, 0)`).
     * @param canvasHeight Same as [canvasWidth] but for height / the y-axis.
     * @return A complete, self-contained SVG document as a string (UTF-8 text, not encoded).
     */
    fun toSvg(
        paths: List<PathData>,
        canvasWidth: Float? = null,
        canvasHeight: Float? = null
    ): String {
        val (boundW, boundH) = boundingSize(paths)
        val width = canvasWidth ?: boundW
        val height = canvasHeight ?: boundH

        val sb = StringBuilder()
        sb.append("<svg xmlns=\"http://www.w3.org/2000/svg\" ")
        sb.append("viewBox=\"0 0 ${width.fmt()} ${height.fmt()}\" ")
        sb.append("width=\"${width.fmt()}\" height=\"${height.fmt()}\">\n")

        for (path in paths) {
            if (path.paths.isEmpty()) continue
            val rgb = "#" + (path.color.toArgb() and 0x00FFFFFF).toUInt().toString(16).padStart(6, '0')
            val alpha = path.color.alpha
            sb.append("  <path d=\"${pathData(path.paths)}\" ")
            sb.append("fill=\"none\" stroke=\"$rgb\" ")
            sb.append("stroke-opacity=\"${alpha.fmt()}\" ")
            sb.append("stroke-width=\"${path.thickness.fmt()}\" ")
            sb.append("stroke-linecap=\"round\" stroke-linejoin=\"round\"/>\n")
        }

        // Lossless payload — the ONLY thing fromSvg() will trust as editable data.
        sb.append("  <metadata id=\"drawingData\"><![CDATA[\n")
        sb.append(encodeMetadata(width, height, paths))
        sb.append("  ]]></metadata>\n")
        sb.append("</svg>")
        return sb.toString()
    }

    /**
     * Parses an SVG string back into an editable [DrawingData], but ONLY if it
     * contains this class's own embedded `<metadata>` block (see [encodeMetadata] for
     * the format).
     *
     * This intentionally does not attempt to reconstruct strokes from `<path>` geometry.
     * An SVG attachment may have been edited, replaced, or created by a different CalDAV
     * client — its path data could use curves, transforms, groups, multiple subpaths, or
     * anything else valid SVG allows, none of which reliably maps back to `PathData`.
     * Rather than guess and risk silently corrupting or misrepresenting that data, this
     * function refuses to touch it.
     *
     * @param svg The SVG document string to parse.
     * @return The reconstructed, editable [DrawingData] if — and only if — a valid
     *   metadata block produced by [toSvg] is present. Returns `null` for any other SVG
     *   (foreign, hand-edited, corrupted, or missing the block entirely); the caller
     *   should treat a `null` result as "render this attachment as a flat, read-only
     *   image, don't offer stroke-level editing."
     */
    fun fromSvg(svg: String): DrawingData? = parseMetadata(svg)

