    /**
     * Formats a [Float] as a compact decimal string (rounded to 2 decimal places, with
     * trailing `.0` dropped for whole numbers) without relying on `java.util.Locale` or
     * `String.format`, neither of which is safely available across all Kotlin Multiplatform
     * targets.
     *
     * @receiver The value to format.
     * @return The formatted string, e.g. `12.3`, `100`, `-4.05`.
     */
    private fun Float.fmt(): String {
        val rounded = round(this * 100f) / 100f
        return if (rounded == rounded.toLong().toFloat()) {
            rounded.toLong().toString()
        } else {
            rounded.toString()
        }
    }
