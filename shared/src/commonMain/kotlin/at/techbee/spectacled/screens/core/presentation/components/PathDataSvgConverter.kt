    // Geometry (write-only) — used to emit <path> elements so any SVG
    // viewer can render the drawing. Never parsed back; see fromSvg().
    // -----------------------------------------------------------------

    /**
     * Builds an SVG path `d` attribute value for one stroke, as a sequence of quadratic
     * Bézier segments: `M x0 y0 Q cx1 cy1 x1 y1 Q cx2 cy2 x2 y2 ...`, where each control
     * point is the midpoint of the two points it connects. This mirrors the smoothing
     * your `DrawingCanvas.drawPath()` composable applies at render time.
     *
     * @param points The stroke's raw points, in order.
     * @return The `d` attribute value (without surrounding quotes), or an empty string
     *   if [points] is empty.
     */
    private fun pathData(points: List<Offset>): String {
        if (points.isEmpty()) return ""
        val sb = StringBuilder("M ${points[0].x.fmt()} ${points[0].y.fmt()} ")
        for (i in 1..points.lastIndex) {
            val from = points[i - 1]
            val to = points[i]
            val cx = (from.x + to.x) / 2
            val cy = (from.y + to.y) / 2
            sb.append("Q ${cx.fmt()} ${cy.fmt()} ${to.x.fmt()} ${to.y.fmt()} ")
        }
        return sb.toString().trim()
    }

    /**
     * Computes a fallback canvas size from the strokes themselves, used by [toSvg] when
     * no explicit `canvasWidth`/`canvasHeight` is supplied.
     *
     * @param paths The strokes to measure.
     * @return The maximum x and y coordinate found across all points (assuming the
     *   canvas origin is `(0, 0)`), or `(0f, 0f)` if [paths] is empty or contains no points.
     */
    private fun boundingSize(paths: List<PathData>): Pair<Float, Float> {
        var maxX = 0f
        var maxY = 0f
        for (path in paths) {
            for (o in path.paths) {
                maxX = max(maxX, o.x)
                maxY = max(maxY, o.y)
            }
        }
        return maxX to maxY
    }

    // -----------------------------------------------------------------
    // Lossless metadata block: simple line-based format, no JSON/XML lib
    // needed. Example:
    //
    //   W:800.0,600.0
    //   S:2026-07-02T10:15:30.123Z|FF000000|5.0
    //   12.0,8.5
    //   14.2,9.1
    //   S:2026-07-02T10:15:31.987Z|FF3366CC|30.0
    //   ...
    //
    // Note: the "S:" header uses '|' as a separator (not ',') so that `id` values
    // (e.g. ISO timestamps) can't collide with the numeric point lines' ',' separator.
    // If your `id` values could ever contain '|' or a newline, swap in a different
    // delimiter or escape it before relying on this format.
    // -----------------------------------------------------------------

    private val CDATA_REGEX = Regex(
        "<metadata[^>]*>\\s*<!\\[CDATA\\[([\\s\\S]*?)]]>\\s*</metadata>"
    )

    /**
     * Encodes canvas size and a list of [PathData] as the plain-text payload embedded
     * inside the SVG's `<metadata>` CDATA block.
     *
     * @param canvasWidth Canvas width to record (see [toSvg]).
     * @param canvasHeight Canvas height to record (see [toSvg]).
     * @param paths The strokes to encode.
     * @return The metadata payload text (not yet wrapped in `<metadata>`/`CDATA` tags).
     */
    private fun encodeMetadata(canvasWidth: Float, canvasHeight: Float, paths: List<PathData>): String {
        val sb = StringBuilder()
        sb.append("W:${canvasWidth},${canvasHeight}\n")
        for (path in paths) {
            val colorHex = path.color.toArgb().toUInt().toString(16).padStart(8, '0')
            sb.append("S:${path.id}|$colorHex|${path.thickness}\n")
            for (o in path.paths) {
                sb.append("${o.x},${o.y}\n")
            }
        }
        return sb.toString()
    }

    /**
     * Parses the embedded `<metadata>` CDATA block (see [encodeMetadata] for the format)
     * back into a full-fidelity [DrawingData], if present and well-formed. This is the
     * sole source of truth for [fromSvg] — no other part of the SVG is read.
     *
     * @param svg The SVG document string.
     * @return The reconstructed [DrawingData], or `null` if there is no metadata
     *   block, it's empty, or any line fails to parse (malformed/truncated/foreign
     *   data) — signaling the caller to treat the attachment as non-editable.
     */
    private fun parseMetadata(svg: String): DrawingData? {
        val raw = CDATA_REGEX.find(svg)?.groupValues?.get(1) ?: return null
        val lines = raw.split('\n').map { it.trim() }.filter { it.isNotEmpty() }
        if (lines.isEmpty()) return null

        val result = mutableListOf<PathData>()
        var canvasWidth = 0f
        var canvasHeight = 0f
        var currentId = ""
        var currentColor = Color.Black
        var currentThickness = 0f
        var currentPoints = mutableListOf<Offset>()
        var hasOpenStroke = false

        fun flush() {
            if (hasOpenStroke) {
                result.add(
                    PathData(
                        id = currentId,
                        color = currentColor,
                        thickness = currentThickness,
                        paths = currentPoints.toList()
                    )
                )
            }
        }

        try {
            for (line in lines) {
                when {
                    line.startsWith("W:") -> {
                        val parts = line.removePrefix("W:").split(',')
                        canvasWidth = parts[0].toFloat()
                        canvasHeight = parts[1].toFloat()
                    }
                    line.startsWith("S:") -> {
                        flush()
                        currentPoints = mutableListOf()
                        val parts = line.removePrefix("S:").split('|')
                        currentId = parts[0]
                        currentColor = Color((parts[1].toULong(16)).toInt())
                        currentThickness = parts[2].toFloat()
                        hasOpenStroke = true
                    }
                    else -> {
                        val parts = line.split(',')
                        currentPoints.add(Offset(x = parts[0].toFloat(), y = parts[1].toFloat()))
                    }
                }
            }
            flush()

            if (canvasWidth == 0f || canvasHeight == 0f) {
                val (boundW, boundH) = boundingSize(result)
                canvasWidth = boundW
                canvasHeight = boundH
            }
        } catch (e: Exception) {
            // Malformed or foreign metadata — signal "not editable" rather than guessing.
            return null
        }

        return DrawingData(result.toList(), canvasWidth, canvasHeight)
    }

